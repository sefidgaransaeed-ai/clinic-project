import type { MetadataRoute } from "next";

// تصمیم 0009: تا پیش از راه‌اندازی واقعی، سایت نباید در موتورهای جست‌وجو
// فهرست شود. نام و شماره نظام پزشکی واقعی پزشک روی صفحه می‌آید و بدون این،
// جست‌وجوی نام ایشان می‌توانست بیمار واقعی را به سایت نیمه‌ساخته برساند.
// هنگام راه‌اندازی واقعی این فایل برداشته می‌شود — چک‌لیست p1-17.
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      disallow: "/",
    },
  };
}
