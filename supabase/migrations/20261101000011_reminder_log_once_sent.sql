-- ============================================================================
-- جلوگیری از ارسال دوبارهٔ یادآوری — پیشنهاد خانم مریم در کار p2-13
--
-- جدول reminder_log هیچ قید یکتایی نداشت، پس اگر زمان‌بند دوبار اجرا می‌شد
-- یا یک اجرا نیمه‌کاره می‌ماند، یادآوری یک نوبت دوبار می‌رفت.
--
-- چرا قید یکتای ساده روی (appointment_id, platform) غلط بود:
-- ستون result سه مقدار دارد — 'sent' و 'failed' و 'no_link'. با قید ساده،
-- یک تلاش ناموفق هم جا را اشغال می‌کرد و دیگر هیچ‌وقت تلاش دوباره ممکن نبود.
-- یعنی اولین خطای شبکه، یادآوری آن نوبت را برای همیشه از بین می‌برد.
--
-- پس قید فقط روی ردیف‌های موفق اعمال می‌شود: هر نوبت روی هر پیام‌رسان
-- حداکثر یک‌بار «فرستاده‌شده»، ولی هر تعداد تلاش ناموفق مجاز است.
-- ============================================================================

create unique index if not exists reminder_log_once_sent
  on public.reminder_log (appointment_id, platform)
  where result = 'sent';

comment on index public.reminder_log_once_sent is
  'سند 0012 — هر نوبت روی هر پیام‌رسان فقط یک یادآوری موفق. تلاش ناموفق محدود نیست.';
