-- پاسخ‌های دقیق با جای‌گذاری دادهٔ زنده — ۶ آذر ۱۴۰۵
--
-- چرا: پزشک گفت پاسخ‌ها باید دقیق و در خود گفت‌وگو باشد، نه ارجاع به صفحه.
-- متن ثابت با مقدار «هاردکد» به اولین تغییر ساعت کاری یا نشانی کهنه می‌شود
-- (همان اتفاقی که با شمارهٔ قدیمی ۰۹۱۲۰۱۴۰۶۳۵ افتاد). پس متن‌ها نشانه می‌گیرند:
--
--   {{phone}}      شمارهٔ تلفن مطب
--   {{hours}}      زمان‌های حضور هر مطب، از جدول working_hours
--   {{addresses}}  نشانی هر مطب، از جدول clinics
--   {{booking}}    دو راه گرفتن نوبت: فرم سایت و تلفن
--
-- پرکردن در کد انجام می‌شود (`src/modules/site/faq-fill.ts`) و هم صفحهٔ پرسش‌ها
-- و هم چت‌بات از همان استفاده می‌کنند. اگر روزی داده کم بود، جملهٔ جایگزین می‌آید،
-- نه نشانهٔ خام.

update public.faq_items
set answer = 'دو راه دارید: {{booking}}.'
where question = 'برای گرفتن نوبت چه کار کنم؟';

update public.faq_items
set answer = 'زمان‌های حضور پزشک: {{hours}}.
برای دیدن برنامهٔ کامل هفته و اطمینان از تعطیلی‌ها، صفحهٔ «تماس» را ببینید.'
where question = 'ساعات کاری مطب چه زمانی است؟';

update public.faq_items
set answer = 'نشانی مطب‌ها: {{addresses}}.'
where question = 'آدرس مطب کجاست؟';

update public.faq_items
set answer = 'شمارهٔ تماس مطب {{phone}} است. واتس‌اپ و اینستاگرام مطب هم در صفحهٔ «تماس» لینک شده‌اند. برای گرفتن نوبت: {{booking}}.'
where question = 'شماره تلفن و راه‌های تماس با مطب چیست؟';

update public.faq_items
set answer = 'برای اطلاع از تعرفهٔ روز با مطب تماس بگیرید: {{phone}}.'
where question = 'هزینه ویزیت چقدر است؟';

-- نام مطب‌ها کلیدواژهٔ پرسش آدرس هم باشند تا «مرزداران» و «ظفر» بی‌پاسخ نمانند
update public.faq_items
set keywords = array(select distinct k from unnest(keywords || array['مطب مرزداران', 'مطب ظفر', 'نشانی مرزداران', 'نشانی ظفر']) as k order by k)
where question = 'آدرس مطب کجاست؟';
